type dynamicUpdateLLM struct {
	customHandler func(systemPrompt, userPrompt string) (string, error)
}

func (d dynamicUpdateLLM) Name() string { return "dynamic-llm" }

func (d dynamicUpdateLLM) GenerateStructured(
	_ context.Context, systemPrompt, userPrompt string, _ any,
) (string, error) {
	if d.customHandler != nil {
		return d.customHandler(systemPrompt, userPrompt)
	}
	if strings.Contains(systemPrompt, "reconciling OpenAPI") {
		return `{"global_notes":[],"overrides":[],"ambiguities":[],"missing_info":[],"requirements_language":"English"}`, nil
	}
	if strings.Contains(systemPrompt, "reusable setup") {
		return `{"seed":{},"setup":{},"unresolved":[],"assumptions":[]}`, nil
	}
	if strings.Contains(systemPrompt, "writing the narrative analysis") {
		return `{"analysis":"Generated by test.","assumptions":[]}`, nil
	}
	if strings.Contains(systemPrompt, "designing test scenarios") {
		return `{"api":"GET {default}/users","scenarios":[{"id":"users-get","name":"Get users","steps":[{"call":"GET {default}/users","expect":200,"save":{"user_id":"body.id"}}]}]}`, nil
	}
	switch systemPrompt {
	case updateScenarioSystemPrompt:
		if strings.Contains(userPrompt, "GET {default}/other") {
			return `{"scenarios":[{"id":"get-other","steps":[{"call":"GET {default}/other","expect":200}]}]}`, nil
		}
		if strings.Contains(userPrompt, "POST {default}/users") {
			return `{"scenarios":[{"id":"post-users","steps":[{"call":"POST {default}/users","expect":201,"body":{"name":"Alice"}}]}]}`, nil
		}
		return `{"scenarios":[{"id":"users-get","steps":[{"call":"GET {default}/users","expect":200,"save":{"user_id":"body.id"}}]}]}`, nil
	case updateSetupSystemPrompt:
		return `{"vars":{"token":"test-token"},"steps":[{"call":"POST {default}/auth/login","expect":200,"save":{"jwt":"body.token"}}]}`, nil
	default:
		return "", fmt.Errorf("unexpected prompt: %s", systemPrompt)
	}
}

func TestExecuteUpdate_CompatibleAPIChange_NoSuiteMutation(t *testing.T) {
	dir := t.TempDir()
	v1Path := filepath.Join(dir, "openapi_v1.yaml")
	_ = os.WriteFile(v1Path, []byte(updateOpenAPIV1), 0o644)
	outDir := filepath.Join(dir, "out")

	// 1. Initial run
	store := suitefile.NewStore()
	g := NewGenerator(dynamicUpdateLLM{}, sources.NewLoader(), store, smokeClock{})
	initReq := Request{
		Mode:        ModeInitial,
		APIs:        []domain.APIInput{{Server: "default", Path: v1Path}},
		OutputDir:   outDir,
		Concurrency: 1,
	}
	_, err := g.Execute(context.Background(), initReq)
	if err != nil {
		t.Fatalf("Execute initial failed: %v", err)
	}

	loadedInit, err := store.Load(context.Background(), outDir)
	if err != nil {
		t.Fatalf("Load initial failed: %v", err)
	}
	initialHash := domain.SuiteHash(loadedInit.Suite)

	// 2. Update with compatible change (V2)
	v2Path := filepath.Join(dir, "openapi_v2.yaml")
	_ = os.WriteFile(v2Path, []byte(updateOpenAPIV2_Compatible), 0o644)

	updateReq := Request{
		Mode:        ModeUpdate,
		APIs:        []domain.APIInput{{Server: "default", Path: v2Path}},
		OutputDir:   outDir,
		Concurrency: 1,
	}
	res, err := g.Execute(context.Background(), updateReq)
	if err != nil {
		t.Fatalf("Execute update failed: %v", err)
	}

	if res.Mode != ModeUpdate {
		t.Errorf("expected ModeUpdate, got %v", res.Mode)
	}
	if res.SuiteChanged {
		t.Errorf("compatible change should not mutate suite")
	}
	if res.UpdateN != 1 {
		t.Errorf("expected UpdateN=1, got %d", res.UpdateN)
	}
	if len(res.Impact.Scenarios) == 0 {
		t.Errorf("expected non-empty scenario impact for changed API")
	}

	// 3. Verify suite file on disk has same hash, log file has 1 update entry
	loadedUpdated, err := store.Load(context.Background(), outDir)
	if err != nil {
		t.Fatalf("Load updated failed: %v", err)
	}
	if domain.SuiteHash(loadedUpdated.Suite) != initialHash {
		t.Errorf("suite hash changed unexpectedly")
	}
	if len(loadedUpdated.Log.Update) != 1 {
		t.Fatalf("expected 1 update entry in log, got %d", len(loadedUpdated.Log.Update))
	}
	entry := loadedUpdated.Log.Update[0]
	if entry.N != 1 {
		t.Errorf("entry N = %d, want 1", entry.N)
	}
	if len(entry.Impact.Scenarios) == 0 {
		t.Errorf("entry Impact.Scenarios must not be empty")
	}
	if entry.AfterHash != initialHash {
		t.Errorf("entry AfterHash = %q, want %q", entry.AfterHash, initialHash)
	}
}

