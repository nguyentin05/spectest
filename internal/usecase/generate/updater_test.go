func TestExecuteUpdate_AddedAPI_CreatesScenarioAndSelectsInRun(t *testing.T) {
	dir := t.TempDir()
	v1Path := filepath.Join(dir, "openapi_v1.yaml")
	_ = os.WriteFile(v1Path, []byte(updateOpenAPIV1), 0o644)
	outDir := filepath.Join(dir, "out")

	store := suitefile.NewStore()
	g := NewGenerator(dynamicUpdateLLM{}, sources.NewLoader(), store, smokeClock{})
	initReq := Request{
		Mode:        ModeInitial,
		APIs:        []domain.APIInput{{Server: "default", Path: v1Path}},
		OutputDir:   outDir,
		Concurrency: 1,
	}
	if _, err := g.Execute(context.Background(), initReq); err != nil {
		t.Fatalf("Execute initial failed: %v", err)
	}

	// Update with added POST /users endpoint
	v2Path := filepath.Join(dir, "openapi_v2_added.yaml")
	_ = os.WriteFile(v2Path, []byte(updateOpenAPIV2_Added), 0o644)

	updateReq := Request{
		Mode:        ModeUpdate,
		APIs:        []domain.APIInput{{Server: "default", Path: v2Path}},
		OutputDir:   outDir,
		Concurrency: 1,
	}
	res, err := g.Execute(context.Background(), updateReq)
	if err != nil {
		t.Fatalf("Execute update failed: %v", err)
	}

	if !res.SuiteChanged {
		t.Errorf("expected SuiteChanged=true when new API added")
	}
	if res.UpdateN != 1 {
		t.Errorf("expected UpdateN=1, got %d", res.UpdateN)
	}

	loaded, err := store.Load(context.Background(), outDir)
	if err != nil {
		t.Fatalf("Load failed: %v", err)
	}

	// Verify new scenario exists in suite
	var foundNewScenario bool
	for _, sc := range loaded.Suite.Scenarios {
		if sc.ID == "post-users" || strings.Contains(sc.ID, "post") {
			foundNewScenario = true
			if len(sc.Steps) == 0 || sc.Steps[0].Call != "POST {default}/users" {
				t.Errorf("unexpected steps for created scenario: %+v", sc.Steps)
			}
		}
	}
	if !foundNewScenario {
		t.Errorf("expected new scenario for POST {default}/users in updated suite")
	}

	// Verify Create in history log
	if len(loaded.Log.Update) != 1 {
		t.Fatalf("expected 1 update entry, got %d", len(loaded.Log.Update))
	}
	entry := loaded.Log.Update[0]
	if entry.Create == nil || len(entry.Create.Scenarios) == 0 {
		t.Fatalf("expected Create.Scenarios in log entry, got %+v", entry.Create)
	}

	// Verify only-changed selection includes the created scenario
	selectedSuite, sel, err := ucrun.SelectLatestUpdateScenarios(loaded.Suite, loaded.Log)
	if err != nil {
		t.Fatalf("SelectLatestUpdateScenarios failed: %v", err)
	}
	if len(selectedSuite.Scenarios) == 0 {
		t.Fatalf("expected scenarios selected for run, got 0")
	}
	foundInSelected := false
	for _, sc := range selectedSuite.Scenarios {
		if sc.ID == entry.Create.Scenarios[0].ID {
			foundInSelected = true
		}
	}
	if !foundInSelected {
		t.Errorf("expected created scenario %q to be selected in run, selected IDs: %v", entry.Create.Scenarios[0].ID, sel.ScenarioIDs)
	}
}

